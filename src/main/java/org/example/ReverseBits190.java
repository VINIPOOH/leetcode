package org.example;

public class ReverseBits190 {

    //короткое
    public int reverseBits1(int n) {
        int result = 0;
        for (int i = 0; i < 32; i++) {
            result = (result << 1) | (n & 1);
            n >>>= 1; // ВАЖНО: беззнаковый сдвиг
        }
        return result;
    }

    //пошаговое решение что б было понятно
    public int reverseBits(int n) {
        int toReturn = 0;
        for (int i = 0; i < 32; i++) {
            toReturn <<= 1; //двигаем на 1 бит массив результата
            int bitToAdd = n & 1; //получаем последний бит
            toReturn |= bitToAdd; //добавляем его к результату
            n >>>= 1;//двигаем дано на следующий бит без сохранения знака
        }
        return toReturn;
    }

    //Разворот с кешем
    //В кеше мы храним по сути мапу развернутых байтов.
    //Индекс исходное значение, значение результат разворота индекса
    //___________________________________________________________________________
    private static final int[] cache = new int[256];

    static {
        for (int i = 0; i < 256; i++) {
            cache[i] = reverseByte(i);
        }
    }

    public int reverseBitsWithCash(int n) {
        //теперь берем каждый бит исходного числа получаем его оборот с кеша и дальше сдвигаем его на нужную позицию.
        return (cache[n & 0xFF] << 24) |
                (cache[(n >>> 8) & 0xFF] << 16) |
                (cache[(n >>> 16) & 0xFF] << 8) |
                (cache[(n >>> 24) & 0xFF]);
    }

    private static int reverseByte(int b) {
        int res = 0;
        for (int i = 0; i < 8; i++) {
            res = (res << 1) | (b & 1);
            b >>= 1;
        }
        return res;
    }
    //___________________________________________________________________________
    
    //супер оптимизированное. Разворачиваем по частям масками
    public int reverseBits16(int n) {
        n = (n >>> 16) | (n << 16);

        n = ((n & 0xff00ff00) >>> 8)  | ((n & 0x00ff00ff) << 8);
        n = ((n & 0xf0f0f0f0) >>> 4)  | ((n & 0x0f0f0f0f) << 4);
        n = ((n & 0xcccccccc) >>> 2) | ((n & 0x33333333) << 2);
        n = ((n & 0xaaaaaaaa) >>> 1) | ((n & 0x55555555) << 1);

        return n;
    }

    //то же самое, но маски двоичные
    public int reverseBits2(int n) {
        // меняем местами 16-битные половины
        n = (n >>> 16) | (n << 16);

        // меняем местами 8-битные блоки
        n = ((n & 0b11111111000000001111111100000000) >>> 8) |
                ((n & 0b00000000111111110000000011111111) << 8);

        // меняем местами 4-битные куски (нибблы)
        n = ((n & 0b11110000111100001111000011110000) >>> 4) |
                ((n & 0b00001111000011110000111100001111) << 4);

        // меняем местами пары битов
        n = ((n & 0b11001100110011001100110011001100) >>> 2) |
                ((n & 0b00110011001100110011001100110011) << 2);

        // меняем местами отдельные биты
        n = ((n & 0b10101010101010101010101010101010) >>> 1) |
                ((n & 0b01010101010101010101010101010101) << 1);

        return n;
    }
}
